
# 1 to 20 number print using for loop

for i in range(1,21):
    print(i)

# Even number and Odd number

for i in range(2,21,2):
    print(i)

for i in range(1,21,2):
    print(i)

# count backwards

for i in range(20,0,-1):
    print(i)

# print multiples of 5

for i in range(5,51,5):
    print(i)

# calculate sum from 1 to 10

total = 0

